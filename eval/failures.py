"""Failure analysis: render the worst cases of E2, E3, E4 and E8 as images, for diagnosis.

Images are video frames, so they go to data/failures/ (gitignored, CLAUDE.md rule 4) and are
regenerated by this script. The one-line diagnoses are written by a person looking at them,
in results/failures.md (committed).

Each panel is a crop around the player: green = Aamir's labelled points, orange = the
system's points on that frame (kicking leg drawn thicker), with a caption.

    uv run python -m eval.failures
"""

from __future__ import annotations

import csv
import json
from pathlib import Path

import numpy as np
from PIL import Image, ImageDraw, ImageFont

from eval import v1_replica
from kickcoach.ingest import load_meta
from kickcoach.labels import schema
from kickcoach.pose import cache, skeleton
from kickcoach.signal import clean

ROOT = Path(__file__).resolve().parents[1]
RESULTS = ROOT / "results"
OUT = ROOT / "data" / "failures"
FRAMES = ROOT / "data" / "frames"
BONES = (
    ("shoulder", "hip"),
    ("hip", "knee"),
    ("knee", "ankle"),
    ("ankle", "heel"),
    ("heel", "big_toe"),
    ("ankle", "big_toe"),
)
LABEL_RGB, SYSTEM_RGB = (40, 220, 90), (255, 140, 0)
PANEL_H = 420
N_WORST = 4


def frame_img(cid: str, t: int) -> Image.Image:
    return Image.open(FRAMES / cid / f"{t:06d}.jpg").convert("RGB")


def label_points(lab: dict, t: int) -> dict[str, np.ndarray]:
    e = lab["frames"].get(str(t))
    if not e:
        return {}
    return {n: np.array([p["x"], p["y"]]) for n, p in e["points"].items() if p["v"]}


def array_points(xy: np.ndarray, t: int) -> dict[str, np.ndarray]:
    out = {}
    for n in (*schema.POINTS,):
        p = xy[t, skeleton.INDEX[n], :2].astype(float)
        if np.isfinite(p).all():
            out[n] = p
    return out


def _draw(d: ImageDraw.ImageDraw, pts: dict, rgb, leg: str | None, scale: float, off) -> None:
    def at(n):
        return tuple((pts[n] - off) * scale)

    for side in ("left", "right"):
        w = 4 if side == leg else 2
        for a, b in BONES:
            na, nb = f"{side}_{a}", f"{side}_{b}"
            if na in pts and nb in pts:
                d.line([at(na), at(nb)], fill=rgb, width=w)
    for n in pts:
        if n == "ball":
            continue
        x, y = at(n)
        d.ellipse([x - 3, y - 3, x + 3, y + 3], outline=rgb, width=2)


def panel(
    cid: str,
    t: int,
    caption: str,
    *,
    label: dict | None = None,
    system: dict | None = None,
    leg: str | None = None,
    box: tuple[float, float, float, float] | None = None,
) -> Image.Image:
    """A crop of frame ``t`` around the given points (or ``box``), scaled to PANEL_H."""
    img = frame_img(cid, t)
    pts = [*(label or {}).values(), *(system or {}).values()]
    if box is None and pts:
        p = np.array(pts)
        lo, hi = p.min(0), p.max(0)
        c, half = (lo + hi) / 2, max(*(hi - lo), 80) * 0.8
        box = (c[0] - half, c[1] - half, c[0] + half, c[1] + half)
    if box is None:
        box = (0, 0, img.width, img.height)
    x0, y0 = max(0, box[0]), max(0, box[1])
    x1, y1 = min(img.width, box[2]), min(img.height, box[3])
    crop = img.crop((int(x0), int(y0), int(x1), int(y1)))
    scale = PANEL_H / crop.height
    crop = crop.resize((max(1, round(crop.width * scale)), PANEL_H))
    d = ImageDraw.Draw(crop)
    if label:
        _draw(d, label, LABEL_RGB, leg, scale, np.array([int(x0), int(y0)]))
    if system:
        _draw(d, system, SYSTEM_RGB, leg, scale, np.array([int(x0), int(y0)]))
    out = Image.new("RGB", (max(crop.width, 360), PANEL_H + 40), "white")
    out.paste(crop, (0, 40))
    font = ImageFont.load_default(size=13)
    ImageDraw.Draw(out).multiline_text((4, 2), caption, fill="black", font=font, spacing=2)
    return out


def strip(panels: list[Image.Image], path: Path) -> Path:
    w = sum(p.width for p in panels) + 6 * (len(panels) - 1)
    out = Image.new("RGB", (w, max(p.height for p in panels)), "white")
    x = 0
    for p in panels:
        out.paste(p, (x, 0))
        x += p.width + 6
    path.parent.mkdir(parents=True, exist_ok=True)
    out.save(path)
    return path


def _csv(name: str) -> list[dict]:
    with open(RESULTS / name, newline="") as f:
        return list(csv.DictReader(f))


def _num(x: str) -> float | None:
    return None if x in ("", "None") else float(x)


def _cleaned(cid: str, contact: int | None) -> np.ndarray:
    meta = load_meta(FRAMES / cid)
    spf = meta["seconds_per_frame"] if meta.get("fps_trusted") else None
    breaks = (contact,) if contact is not None else ()
    return clean(cache.load("rtmpose", cid), seconds_per_frame=spf, breaks=breaks).xy


def e2_cases(labels: dict) -> list[tuple[str, Path]]:
    rows = [
        r
        for r in _csv("e2.csv")
        if r["view"] == "end_to_end" and r["system"] == "v2_pipeline" and r["err"]
    ]
    rows.sort(key=lambda r: -abs(float(r["err"])))
    out = []
    for r in rows[:N_WORST]:
        cid, lab = r["clip_id"], labels[r["clip_id"]]
        res = json.loads((RESULTS / "pipeline" / f"{cid}.json").read_text())
        xy = _cleaned(cid, res["events"]["contact_frame"])
        leg = lab["clip"]["kicking_leg"]
        tl, ts = int(r["label_frame"]), int(r["system_frame"])
        panels = [
            panel(
                cid,
                tl,
                f"{cid} {r['feature']}: label frame {tl}\ntruth {float(r['truth']):.1f}°",
                label=label_points(lab, tl),
                system=array_points(xy, tl),
                leg=leg,
            ),
            panel(
                cid,
                ts,
                f"pipeline frame {ts}: {float(r['value']):.1f}° (err {float(r['err']):+.1f}°)",
                system=array_points(xy, ts),
                leg=leg,
            ),
        ]
        out.append(
            (f"{cid} {r['feature']}", strip(panels, OUT / "e2" / f"{cid}_{r['feature']}.png"))
        )
    return out


def e3_cases(labels: dict) -> list[tuple[str, Path]]:
    rows = [r for r in _csv("e3.csv") if r["method"] == "v2_pipeline" and r["err"] not in ("", "0")]
    rows.sort(key=lambda r: -abs(int(r["err"])))
    out = []
    for r in rows[:N_WORST]:
        cid, lab = r["clip_id"], labels[r["clip_id"]]
        tl, ts = int(r["label_frame"]), int(r["frame"])
        xy = _cleaned(cid, None)
        leg = lab["clip"]["kicking_leg"]
        pts = {**label_points(lab, tl), **array_points(xy, tl)}
        p = np.array(list(pts.values()))
        c, half = p.mean(0), max(*(p.max(0) - p.min(0)), 80) * 0.8
        box = (c[0] - half, c[1] - half, c[0] + half, c[1] + half)
        panels = [
            panel(cid, t, f"{cid} frame {t} ({name})", system=array_points(xy, t), leg=leg, box=box)
            for t, name in sorted(
                {
                    (tl - 1, "label - 1"),
                    (tl, "labelled contact"),
                    (ts, f"detected, err {int(r['err']):+d}"),
                }
            )
        ]
        out.append((f"{cid} contact {r['err']}", strip(panels, OUT / "e3" / f"{cid}_contact.png")))
    return out


def e8_cases(labels: dict) -> list[tuple[str, Path]]:
    out = []
    gate = {r["clip_id"]: r for r in _csv("e8_gate.csv")}
    for cid in ("c06", "c23"):  # nearest the view threshold on each side (results/e8_summary.md)
        res = json.loads((RESULTS / "pipeline" / f"{cid}.json").read_text())
        t = res["events"]["contact_frame"]
        xy = _cleaned(cid, None)
        pts = array_points(xy, t)
        caption = (
            f"{cid} view_ok_human={gate[cid]['view_ok_human']} ratio "
            f"{float(gate[cid]['viewpoint_ratio']):.3f} (threshold 0.5), frame {t}"
        )
        out.append(
            (
                f"{cid} gate",
                strip([panel(cid, t, caption, system=pts)], OUT / "e8" / f"{cid}_gate.png"),
            )
        )
    bounds = [
        r for r in _csv("e8_bounds.csv") if r["system"] == "v1" and r["beyond_bound"] == "True"
    ]
    bounds.sort(key=lambda r: -abs(float(r["value"])))
    for r in bounds[:2]:
        cid, t = r["clip_id"], int(r["frame"])
        poses = cache.load(v1_replica.CACHE_MODEL, cid)
        panels = [
            panel(
                cid,
                f,
                f"{cid} v1 frame {f}"
                + (f": knee velocity {float(r['value']):g}°/s" if f == t else ""),
                system=array_points(poses[..., :2], f),
            )
            for f in (t - 1, t)
        ]
        out.append((f"{cid} v1 velocity", strip(panels, OUT / "e8" / f"{cid}_v1_velocity.png")))
    return out


def e4_cases(labels: dict) -> list[tuple[str, Path]]:
    path = RESULTS / "e4.csv"
    if not path.exists():
        return []
    rows = [r for r in _csv("e4.csv") if r["knee_angle_contact_gemini_err"] not in ("", "None")]
    rows.sort(key=lambda r: -abs(float(r["knee_angle_contact_gemini_err"])))
    out = []
    for r in rows[:N_WORST]:
        cid, lab = r["clip_id"], labels[r["clip_id"]]
        tl = int(r["contact_label"])
        tg = int(float(r["contact_gemini"])) if r["contact_gemini"] not in ("", "None") else tl
        lp = label_points(lab, tl)
        p = np.array(list(lp.values()))
        c, half = p.mean(0), max(*(p.max(0) - p.min(0)), 80) * 0.8
        box = (c[0] - half, c[1] - half, c[0] + half, c[1] + half)
        panels = [
            panel(
                cid,
                tl,
                f"{cid} labelled contact {tl}: knee {float(r['knee_angle_contact_truth']):.1f}°",
                label=lp,
                leg=lab["clip"]["kicking_leg"],
                box=box,
            ),
            panel(
                cid,
                min(tg, lab["n_frames"] - 1),
                f"Gemini's contact {tg}: knee "
                f"{float(r['knee_angle_contact_gemini']):.0f}° (err "
                f"{float(r['knee_angle_contact_gemini_err']):+.1f}°)",
                box=box,
            ),
        ]
        out.append((f"{cid} gemini knee", strip(panels, OUT / "e4" / f"{cid}_knee.png")))
    return out


def main() -> None:
    labels = schema.load_all()
    for name, fn in (("E2", e2_cases), ("E3", e3_cases), ("E8", e8_cases), ("E4", e4_cases)):
        for what, path in fn(labels):
            print(f"{name} {what}: {path.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
