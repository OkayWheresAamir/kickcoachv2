def run_steps() -> None:
    env = {**os.environ, "GEMINI_API_KEY": ""}
    for name, args in STEPS:
        t0 = time.time()
        p = subprocess.run(
            [sys.executable, *args], cwd=ROOT, env=env, capture_output=True, text=True
        )
        if p.returncode != 0:
            sys.exit(f"step failed: {name}\n{p.stdout[-2000:]}\n{p.stderr[-4000:]}")
        print(f"{name}: {time.time() - t0:.0f} s", flush=True)


# --- reading the outputs ---------------------------------------------------------------


def read_csv(name: str) -> list[dict]:
    path = RESULTS / name
    if not path.exists():
        return []
    with open(path, newline="") as f:
        return list(csv.DictReader(f))


def num(s: str | None) -> float | None:
    return None if s in (None, "") else float(s)


def is_number(s: str) -> bool:
    try:
        float(s)
    except ValueError:
        return False
    return True


def truthy(s: str) -> bool:
    return s == "True"


def pct(k: int, n: int) -> str:
    return f"{100 * k / n:.0f}%" if n else "–"


def deg(x: float | None, signed: bool = False) -> str:
    if x is None or np.isnan(x):
        return "–"
    return f"{x:+.1f}°" if signed else f"{x:.1f}°"


def mae(errs: list[float]) -> float:
    return float(np.mean(np.abs(errs))) if errs else float("nan")


def bias(errs: list[float]) -> float:
    return float(np.mean(errs)) if errs else float("nan")


def ci(c: tuple[float, float], signed: bool = False) -> str:
    f = "{:+.1f}" if signed else "{:.1f}"
    return f"{f.format(c[0])} to {f.format(c[1])}"


# --- the dataset -----------------------------------------------------------------------


def dataset(manifest: dict, labels: dict) -> dict:
    ev = [c for c, m in manifest.items() if m["purpose"] == "eval"]
    kp_clips = [
        c
        for c in ev
        if any(e.get("confirmed") for e in labels.get(c, {}).get("frames", {}).values())
    ]
    frames = [e for c in kp_clips for e in labels[c]["frames"].values() if e.get("confirmed")]
    points = sum(1 for e in frames for n in schema.POINTS if e["points"].get(n, {}).get("v", 0) > 0)
    return {
        "clips": len(manifest),
        "eval": len(ev),
        "tune": sum(manifest[c]["split"] == "tune" for c in ev),
        "heldout": sum(manifest[c]["split"] == "heldout" for c in ev),
        "gate_only": sum(m["purpose"] == "gate_only" for m in manifest.values()),
        "kp_clips": len(kp_clips),
        "kp_heldout": sum(manifest[c]["split"] == "heldout" for c in kp_clips),
        "frames": len(frames),
        "points": points,
        "contact": sum(
            labels.get(c, {}).get("clip", {}).get("contact_frame") is not None for c in ev
        ),
        "view_ok": sum(
            labels.get(c, {}).get("clip", {}).get("view_ok_human") in ("y", "n") for c in manifest
        ),
    }


