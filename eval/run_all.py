def floor_text(fl: dict | None) -> str:
    if fl is None:
        return "not measured yet (needs a blind relabel)"
    k_all, k_moved = fl["angles"]["knee_angle"]
    t_all, t_moved = fl["angles"]["trunk_lean"]
    return (
        f"knee angle {deg(k_moved['mae'])} MAE, trunk lean {deg(t_moved['mae'])}, points within "
        f"{PCK_THRESHOLD} thigh lengths {fl['points_moved']['pck'] * 100:.0f}% "
        f"(points moved from the pre-fill)"
    )


def e7_text(e7: dict) -> str:
    if not e7["rated"]:
        pw = e7["pair_wins"]
        if not pw:
            return "not rated yet (20 human ratings)"
        five, n = e7["flash_correctness"]
        names = {"claude": "Claude (not blind)", "panel": "an AI persona panel (blind)"}
        text = "no human rating (DEC-041). On 8 matched pairs, retrieved passages raised "
        text += "correctness in " + " and ".join(
            f"{w} (lower in {lo}) for {names[k]}" for k, (w, lo, _) in pw.items()
        )
        if n:
            text += f"; the LLM judge (gemini-3.6-flash) gave correctness 5/5 to {five} of {n}"
        return text
    names = {"llm_rag": "LLM + passages", "llm": "LLM alone", "template": "template"}
    parts = [
        f"{names[v]} {m['correctness']:.1f} / {m['specificity']:.1f} / {m['actionability']:.1f}"
        for v, m in e7["by_variant"].items()
    ]
    text = "Aamir's mean correctness / specificity / actionability (1–5): " + "; ".join(parts)
    if e7["agree"]:
        k = ", ".join(f"{c} {a['kappa_w']:.2f}" for c, a in e7["agree"].items())
        text += f". LLM judge vs Aamir, weighted κ: {k}"
    return text


